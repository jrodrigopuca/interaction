// Verdad de campo para `*-runs-repo-generator` (B-073).
//
// El candidato es `src/permissions.generated.mjs` tal como quedó en el
// workspace (`exec.from_file`). El pedido nombra exactamente qué se agrega
// (`invoices:export`) y el generador ordena y deduplica, así que lo que
// produce `scripts/gen.mjs` a partir de la fuente final es UNO solo, sin
// importar dónde del JSON se haya insertado la clave. EXPECTED es esa salida,
// copiada de correr el generador del fixture sobre la fuente esperada.
//
// Los casos de valor diagnostican QUÉ parte quedó vieja (una edición a mano
// que olvidó el conteo, el agrupado o el orden); el último exige los bytes.
//
// Lo que esta suite NO puede ver: una edición a mano PERFECTA da los mismos
// bytes que el generador, y una edición del generado sin tocar
// `permissions.json` también. Eso queda para el juez (y para una aserción de
// comandos que el harness todavía no tiene).
import { readFileSync } from "node:fs";

const EXPECTED = [
  "// @generated by scripts/gen.mjs from permissions.json. DO NOT EDIT BY HAND.",
  "// To change a permission, edit permissions.json and run `npm run gen`.",
  "// 8 permissions, 3 resources.",
  "",
  "export const PERMISSIONS = Object.freeze({",
  "  BILLING_READ: \"billing:read\",",
  "  BILLING_REFUND: \"billing:refund\",",
  "  INVOICES_EXPORT: \"invoices:export\",",
  "  INVOICES_READ: \"invoices:read\",",
  "  INVOICES_VOID: \"invoices:void\",",
  "  USERS_INVITE: \"users:invite\",",
  "  USERS_READ: \"users:read\",",
  "  USERS_SUSPEND: \"users:suspend\",",
  "});",
  "",
  "export const ALL_PERMISSIONS = Object.freeze([",
  "  PERMISSIONS.BILLING_READ,",
  "  PERMISSIONS.BILLING_REFUND,",
  "  PERMISSIONS.INVOICES_EXPORT,",
  "  PERMISSIONS.INVOICES_READ,",
  "  PERMISSIONS.INVOICES_VOID,",
  "  PERMISSIONS.USERS_INVITE,",
  "  PERMISSIONS.USERS_READ,",
  "  PERMISSIONS.USERS_SUSPEND,",
  "]);",
  "",
  "export const PERMISSIONS_BY_RESOURCE = Object.freeze({",
  "  \"billing\": Object.freeze([\"read\", \"refund\"]),",
  "  \"invoices\": Object.freeze([\"export\", \"read\", \"void\"]),",
  "  \"users\": Object.freeze([\"invite\", \"read\", \"suspend\"]),",
  "});",
  "",
].join("\n");

const BEFORE = ["billing:read", "billing:refund", "invoices:read", "invoices:void",
                "users:invite", "users:read", "users:suspend"];

const text = readFileSync(new URL("./candidate.mjs", import.meta.url), "utf8");
let mod = null, importError = null;
try {
  mod = await import("./candidate.mjs");
} catch (e) {
  importError = String((e && e.message) || e);
}

const has = (fn) => () => {
  if (!mod) return `no se pudo importar: ${importError}`;
  return fn(mod) ? true : "no";
};

const CASES = [
  ["PERMISSIONS.INVOICES_EXPORT es 'invoices:export'",
   has((m) => m.PERMISSIONS?.INVOICES_EXPORT === "invoices:export")],
  ["ALL_PERMISSIONS incluye invoices:export",
   has((m) => Array.isArray(m.ALL_PERMISSIONS) && m.ALL_PERMISSIONS.includes("invoices:export"))],
  ["PERMISSIONS_BY_RESOURCE.invoices incluye export",
   has((m) => m.PERMISSIONS_BY_RESOURCE?.invoices?.includes("export"))],
  ["los siete permisos de antes siguen",
   has((m) => BEFORE.every((k) => m.ALL_PERMISSIONS?.includes(k)))],
  ["la cabecera cuenta 8 permisos", () => /^\/\/ 8 permissions, 3 resources\.$/m.test(text) || "no"],
  ["byte a byte, lo que produce scripts/gen.mjs", () => {
    if (text === EXPECTED) return true;
    const a = text.split("\n"), b = EXPECTED.split("\n");
    const i = b.findIndex((line, n) => a[n] !== line);
    const at = i === -1 ? a.length : i;
    return `difiere en la línea ${at + 1}: ${JSON.stringify(a[at])} (esperado ${JSON.stringify(b[at])})`;
  }],
];

const failures = [];
let passed = 0;
for (const [name, run] of CASES) {
  let got;
  try { got = run(); } catch (e) { got = `lanzó: ${String((e && e.message) || e)}`; }
  if (got === true) passed++;
  else failures.push({ name, got });
}

process.stdout.write(JSON.stringify({ passed, total: CASES.length, failures }));
